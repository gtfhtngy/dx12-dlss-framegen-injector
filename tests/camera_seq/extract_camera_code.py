#!/usr/bin/env python3
# Cuts the camera tracker (ScanViewBuffer / TryLegacyLayout / C2pMonitor / CamCutCheck / ParseViewBuffer + their state) out of the REAL src/main.cpp,
# between the  // SN_EXTRACT_BEGIN camera  and  // SN_EXTRACT_END camera  comment markers, so tests/camera_seq runs exactly the code that goes into the DLL.
# Spans between  // SN_EXTRACT_SKIP_BEGIN  and  // SN_EXTRACT_SKIP_END  are left out (the shim provides a stand-in).
# Fails loudly (exit 1) when a marker is missing, duplicated, nested or out of order - so a refactor of main.cpp can never silently shrink the tested region.
# usage: extract_camera_code.py <src dir> <output dir> [region]     region = camera (default, -> camera_extract.inc) | camhold (-> camhold_extract.inc)
import sys, os, hashlib
src, out = sys.argv[1], sys.argv[2]
reg = sys.argv[3] if len(sys.argv) > 3 else 'camera'
lines = open(os.path.join(src, 'main.cpp'), encoding='utf-8').read().split('\n')
def die(msg): print('extract_camera_code: ERROR: ' + msg); sys.exit(1)
begin = [i for i, l in enumerate(lines) if l.startswith('// SN_EXTRACT_BEGIN ' + reg + ' ') or l.rstrip() == '// SN_EXTRACT_BEGIN ' + reg]
end   = [i for i, l in enumerate(lines) if l.startswith('// SN_EXTRACT_END ' + reg + ' ') or l.rstrip() == '// SN_EXTRACT_END ' + reg]
sb    = [i for i, l in enumerate(lines) if l.startswith('// SN_EXTRACT_SKIP_BEGIN')]
se    = [i for i, l in enumerate(lines) if l.startswith('// SN_EXTRACT_SKIP_END')]
if len(begin) != 1 or len(end) != 1: die('need exactly one SN_EXTRACT_BEGIN %s and one SN_EXTRACT_END %s (found %d / %d)' % (reg, reg, len(begin), len(end)))
if not begin[0] < end[0]: die('END marker is before BEGIN marker')
sb = [a for a in sb if begin[0] < a < end[0]]; se = [a for a in se if begin[0] < a < end[0]]   # SKIP spans belong to the region they sit in
if len(sb) != len(se): die('unbalanced SKIP markers (%d begin / %d end)' % (len(sb), len(se)))
for a, b in zip(sb, se):
    if not (begin[0] < a < b < end[0]): die('SKIP span outside the camera region or out of order')
skip = set()
for a, b in zip(sb, se): skip.update(range(a, b + 1))
body = [l for i, l in enumerate(lines) if begin[0] < i < end[0] and i not in skip]
text = '\n'.join(body) + '\n'
os.makedirs(out, exist_ok=True)
open(os.path.join(out, reg + '_extract.inc'), 'w', encoding='utf-8').write('// GENERATED by extract_camera_code.py (region ' + reg + ') from src/main.cpp lines %d-%d - do not edit\n' % (begin[0] + 2, end[0]) + text)
print('extracted camera region of main.cpp (lines %d-%d, %d lines, %d skipped, sha1 %s) -> %s' % (begin[0] + 2, end[0], len(body), len(skip), hashlib.sha1(text.encode()).hexdigest()[:12], out))
